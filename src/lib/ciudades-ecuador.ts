export const CIUDADES_ECUADOR: { nombre: string; provincia: string }[] = Object.entries(
  CIUDADES_POR_PROVINCIA,
)
  .flatMap(([provincia, ciudades]) => ciudades.map((nombre) => ({ nombre, provincia })))
  .sort((a, b) => a.nombre.localeCompare(b.nombre, "es"));

export function normalizarCiudad(texto: string) {
  return texto
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

const CONOCIDAS = new Set([
  ...CIUDADES_ECUADOR.map((c) => normalizarCiudad(c.nombre)),
  "sangorqui",
  "sangolqui",
  "lago agrio",
  "esmeraldas",
]);

/** ¿El texto coincide con una ciudad conocida del Ecuador? Solo sirve para avisar si parece mal escrita. */
export function esCiudadConocida(ciudad: string) {
  return CONOCIDAS.has(normalizarCiudad(ciudad));
}
